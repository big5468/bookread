# Builds the debug APK and runs the JVM unit tests using the toolchain bundled in the repo.
#
# Usage:
#   powershell -File scripts/build-apk.ps1
#   powershell -File scripts/build-apk.ps1 -Tasks ':app:assembleDebug'
#   powershell -File scripts/build-apk.ps1 -Tasks ':app:testDebugUnitTest'
#
# Why this script exists instead of a plain `gradlew assembleDebug`:
#
#  1. Android Studio owns local.properties and rewrites sdk.dir from its own SDK setting, so the
#     build must not depend on that file. ANDROID_HOME is set to the repo-local SDK here.
#  2. The repo-local SDK lives under .tools/ and is git-ignored, together with the Gradle
#     distribution and dependency cache, so no machine-level JDK/SDK setup is required.
#  3. The project path contains non-ASCII characters. Gradle itself copes, but the forked test
#     worker cannot load worker.org.gradle.process.internal.worker.GradleWorkerMain from such a
#     classpath, so the build runs through an ASCII junction. Same reason the Gradle user home and
#     the test JVM's temp directory are ASCII: Windows decodes JVM arguments with the ANSI code
#     page, so a non-ASCII -D value arrives mojibaked.
#  4. Robolectric refuses to start if it cannot create its download lock under user.home or unpack
#     its native SQLite library into java.io.tmpdir, so -PtestHome relocates both.
param(
    [string]$ProjectRoot = (Split-Path $PSScriptRoot -Parent),
    [string]$JavaHome,
    [switch]$NoMirrorPath,
    [Parameter(ValueFromRemainingArguments = $true)]
    [string[]]$Tasks = @(':app:testDebugUnitTest', ':app:assembleDebug')
)

$ErrorActionPreference = 'Stop'
$ProjectRoot = [IO.Path]::GetFullPath($ProjectRoot)

function Test-AsciiPath([string]$Path) { return $Path -match '^[\x00-\x7F]+$' }

# --- ASCII junction for the build path -----------------------------------------------------------------
$buildPath = $ProjectRoot
$junction = $null
if (-not (Test-AsciiPath $ProjectRoot) -and -not $NoMirrorPath) {
    $junction = Join-Path $env:TEMP ('guanjian-build-' + ([guid]::NewGuid().ToString('N').Substring(0, 8)))
    cmd /c mklink /J "$junction" "$ProjectRoot" | Out-Null
    if ($LASTEXITCODE -ne 0) { throw "Could not create junction at $junction" }
    $buildPath = $junction
    Write-Host "Building through ASCII junction: $junction"
}

# --- ASCII Gradle user home and test home --------------------------------------------------------------
# The junction is temporary, so the shared Gradle cache is still addressed through the real project
# path when that path is ASCII; when it is not, go through a stable ASCII junction to it.
$asciiProjectRoot = if (Test-AsciiPath $ProjectRoot) { $ProjectRoot } else {
    $stable = Join-Path $env:TEMP 'guanjian'
    if (-not (Test-Path $stable)) {
        cmd /c mklink /J "$stable" "$ProjectRoot" | Out-Null
        if ($LASTEXITCODE -ne 0) { $stable = $ProjectRoot }
    }
    $stable
}
$gradleUserHome = Join-Path $asciiProjectRoot '.tools/gradle-home'

# AGP prefers local.properties over ANDROID_HOME, and Android Studio keeps rewriting that file from
# its own SDK setting. Pin it to the repo-local SDK for the duration of the build, restoring the
# previous contents afterwards. The path is written with \uXXXX escapes for non-ASCII segments
# because java.util.Properties.load decodes local.properties as ISO-8859-1.
$localPropertiesPath = Join-Path $ProjectRoot 'local.properties'
$localPropertiesBackup = $null
if (Test-Path $localPropertiesPath) {
    $localPropertiesBackup = [IO.File]::ReadAllBytes($localPropertiesPath)
}
$sdkDir = Join-Path $asciiProjectRoot '.tools/sdk'
$escapedSdkDir = -join ($sdkDir.ToCharArray() | ForEach-Object {
    $code = [int][char]$_
    if ($code -eq 92) { '\\' } elseif ($code -gt 127) { '\u{0:X4}' -f $code } else { [string]$_ }
})
$localPropertiesBody = @(
    '## Generated by scripts/build-apk.ps1 for the duration of the build; restored afterwards.',
    '## Do not check in. Android Studio owns the real contents of this file.',
    "sdk.dir=$escapedSdkDir",
    ''
) -join "`r`n"
Set-ItemProperty -Path $localPropertiesPath -Name IsReadOnly -Value $false -ErrorAction SilentlyContinue
[IO.File]::WriteAllText($localPropertiesPath, $localPropertiesBody, [Text.Encoding]::ASCII)

$testHome = Join-Path $env:TEMP 'guanjian-testhome'
New-Item -ItemType Directory -Force "$testHome\tmp" | Out-Null
# Reuse an existing local Maven cache for Robolectric's android-all jars when one is present, so the
# tests need no network access.
$m2 = Join-Path $testHome '.m2/repository'
if (-not (Test-Path $m2)) {
    $source = Join-Path $asciiProjectRoot '.tools/home/.m2/repository'
    if (Test-Path $source) { cmd /c mklink /J "$m2" "$source" | Out-Null }
}

# --- JDK selection -------------------------------------------------------------------------------------
# Explicit parameter, JAVA_HOME, repo-local .tools/jdk, then known local installs.
$candidates = @()
if ($JavaHome) { $candidates += $JavaHome }
if ($env:JAVA_HOME) { $candidates += $env:JAVA_HOME }
$candidates += (Join-Path $ProjectRoot '.tools/jdk')
$candidates += 'D:\soft\java21'
$candidates += 'D:\soft\PyCharm 2025.3.3\jbr'
$resolvedJava = $null
foreach ($candidate in $candidates) {
    if ($candidate -and (Test-Path (Join-Path $candidate 'bin/java.exe'))) {
        # Gradle 8.11.1 supports Java 17-23; Java 24+ is rejected.
        $releaseFile = Join-Path $candidate 'release'
        $major = $null
        if (Test-Path $releaseFile) {
            $match = [regex]::Match((Get-Content $releaseFile -Raw), 'JAVA_VERSION="(\d+)')
            if ($match.Success) { $major = [int]$match.Groups[1].Value }
        }
        if ($null -eq $major -or ($major -ge 17 -and $major -le 23)) { $resolvedJava = $candidate; break }
        Write-Host "Skipping $candidate (Java $major is outside Gradle 8.11.1's supported 17-23 range)."
    }
}
if (-not $resolvedJava) { throw 'No usable JDK found. Install JDK 17-23 or pass -JavaHome.' }
Write-Host "JDK: $resolvedJava"

$gradle = Join-Path $ProjectRoot '.tools/gradle-8.11.1/bin/gradle.bat'
if (-not (Test-Path -LiteralPath $gradle)) { $gradle = Join-Path $ProjectRoot 'gradlew.bat' }

$previousEnvironment = @{}
foreach ($name in @('JAVA_HOME', 'GRADLE_USER_HOME', 'ANDROID_HOME', 'ANDROID_SDK_ROOT', 'ANDROID_USER_HOME', 'ANDROID_PREFS_ROOT')) {
    $previousEnvironment[$name] = [Environment]::GetEnvironmentVariable($name, 'Process')
}

Push-Location $buildPath
try {
    $env:JAVA_HOME = $resolvedJava
    $env:GRADLE_USER_HOME = $gradleUserHome
    $env:ANDROID_HOME = Join-Path $asciiProjectRoot '.tools/sdk'
    $env:ANDROID_SDK_ROOT = $env:ANDROID_HOME
    $env:ANDROID_USER_HOME = Join-Path $asciiProjectRoot '.tools/android-user'
    # Do NOT also set ANDROID_PREFS_ROOT: AGP's PathLocator.singlePathOf() throws when more than one
    # environment variable points at an Android preferences folder.
    New-Item -ItemType Directory -Force $env:ANDROID_USER_HOME | Out-Null

    # The repo-local SDK ships no licenses/ directory. Link the machine's accepted licenses when one
    # exists so AGP does not try to re-download packages into an unwritable system SDK.
    $licenses = Join-Path $env:ANDROID_HOME 'licenses'
    if (-not (Test-Path $licenses)) {
        $systemLicenses = 'D:\soft\ASSDK\licenses'
        if (Test-Path $systemLicenses) { cmd /c mklink /J "$licenses" "$systemLicenses" | Out-Null }
        if (-not (Test-Path $licenses)) { New-Item -ItemType Directory -Force $licenses | Out-Null }
    }
    $analytics = Join-Path $env:ANDROID_USER_HOME 'analytics.settings'
    if (-not (Test-Path $analytics)) { Set-Content -LiteralPath $analytics -Value '{}' -Encoding ASCII }

    # Gradle writes progress to stderr. Windows PowerShell 5.1 turns native stderr into a terminating
    # error while $ErrorActionPreference is 'Stop', so relax it around the call and trust $LASTEXITCODE.
    $ErrorActionPreference = 'Continue'
    & $gradle -p $buildPath @Tasks '--no-daemon' '--no-watch-fs' '--console=plain' `
        '-Pkotlin.compiler.execution.strategy=in-process' "-PtestHome=$testHome"
    $buildExitCode = $LASTEXITCODE
} finally {
    $ErrorActionPreference = 'Stop'
    Pop-Location
    if ($junction -and (Test-Path $junction)) { cmd /c rmdir "$junction" | Out-Null }
    if ($null -ne $localPropertiesBackup) {
        Set-ItemProperty -Path $localPropertiesPath -Name IsReadOnly -Value $false -ErrorAction SilentlyContinue
        [IO.File]::WriteAllBytes($localPropertiesPath, $localPropertiesBackup)
    }
    foreach ($name in $previousEnvironment.Keys) {
        [Environment]::SetEnvironmentVariable($name, $previousEnvironment[$name], 'Process')
    }
}
exit $buildExitCode
